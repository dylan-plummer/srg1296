"""PDS search in G = F_{q1} x ... x F_{qt} (additive), D invariant under
K = < -1, multiplications (x_i) -> (alpha_i x_i) for (alpha_i) in a subgroup S of prod F_{qi}^*,
      optionally one Galois/semilinear map >.
python run_fields.py "2^4,3^4" LOG NPROC TLIM MAXORB
"""
import sys, os, time, math, itertools
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"): os.environ[_v] = "1"
from multiprocessing import Pool
import numpy as np
from abelian_pds import AbelianPDS
from glclasses import irreducibles, companion, order_mod
from fusion import is_srg, graph6


def field_mats(p, e):
    """(C, Fr): multiplication by a primitive element and Frobenius, as e x e matrices over F_p
    acting on column coordinate vectors w.r.t. basis 1, x, ..., x^{e-1}."""
    if e == 1:
        # primitive root mod p
        for g in range(2, p + 1):
            if g % p and all(pow(g, (p - 1) // q, p) != 1 for q in range(2, p) if (p - 1) % q == 0 and all(q % r for r in range(2, q))):
                return np.array([[g % p]]), np.array([[1]])
        return np.array([[1]]), np.array([[1]])
    for f in irreducibles(e, p):
        C = companion(f, p)
        if order_mod(C, p) == p ** e - 1:
            break
    # Frobenius: x^i -> x^{ip}; column i = coordinates of x^{ip}
    def power_vec(k):
        v = np.zeros(e, dtype=np.int64); v[0] = 1
        M = np.linalg.matrix_power  # avoid overflow: iterate
        for _ in range(k):
            v = (C @ v) % p
        return v
    Fr = np.stack([power_vec(i * p) for i in range(e)], axis=1) % p
    return C, Fr


def matpow_mod(M, a, p):
    R = np.eye(M.shape[0], dtype=np.int64); B = M % p; a = int(a)
    while a:
        if a & 1: R = (R @ B) % p
        B = (B @ B) % p; a >>= 1
    return R


def blockdiag(ms):
    n = sum(m.shape[0] for m in ms)
    M = np.zeros((n, n), dtype=np.int64); o = 0
    for m in ms:
        s = m.shape[0]; M[o:o + s, o:o + s] = m; o += s
    return M


def subgroups(mods):
    """all subgroups of Z_m1 x ... x Z_mt generated by <= 2 elements, as generator lists."""
    elems = list(itertools.product(*[range(m) for m in mods]))
    def gen(gs):
        S = {tuple(0 for _ in mods)}
        frontier = list(S)
        while frontier:
            nf = []
            for x in frontier:
                for g in gs:
                    y = tuple((a + b) % m for a, b, m in zip(x, g, mods))
                    if y not in S:
                        S.add(y); nf.append(y)
            frontier = nf
        return frozenset(S)
    cyc = {}
    for g in elems:
        s = gen([g])
        if s not in cyc: cyc[s] = g
    subs = {}
    cl = list(cyc.items())
    for s, g in cl:
        subs.setdefault(s, [g])
    for (s1, g1), (s2, g2) in itertools.combinations(cl, 2):
        if s1 <= s2 or s2 <= s1: continue
        s = gen([g1, g2])
        if s not in subs: subs[s] = [g1, g2]
    return list(subs.values())


def main():
    spec, LOG, NPROC, TLIM, MAXORB = sys.argv[1], sys.argv[2], int(sys.argv[3]), float(sys.argv[4]), int(sys.argv[5])
    fields = [tuple(map(int, s.split("^"))) for s in spec.split(",")]
    v = int(np.prod([p ** e for p, e in fields]))
    prms = []
    for l in open(os.environ.get("SETS", "open_sets.tsv")):
        a, k, la, mu = map(int, l.split())
        if a == v and 2 * k <= v:
            D = (la - mu) ** 2 + 4 * (k - mu); s = math.isqrt(D)
            if s * s == D: prms.append((k, la, mu))
    shape = []
    Cs, Frs = [], []
    for p, e in fields:
        C, Fr = field_mats(p, e)
        Cs.append(C); Frs.append(Fr); shape += [p] * e
    mods = [p ** e - 1 for p, e in fields]
    subs = subgroups(mods)
    # Galois choices: none, or one map acting as Frobenius^{a_i} on factor i
    gal = [None] + [a for a in itertools.product(*[range(e) for p, e in fields]) if any(a)]
    jobs = []
    for gs in subs:
        for g in gal:
            jobs.append((gs, g))
    print(f"v={v} params={prms} subgroups={len(subs)} jobs={len(jobs)}", flush=True)
    global CTX
    CTX = (fields, shape, Cs, Frs, prms, TLIM, MAXORB, v)
    done = set()
    if os.path.exists(LOG):
        for l in open(LOG):
            done.add(l.split("\t")[0])
    jobs = [j for j in jobs if repr(j) not in done]
    with Pool(NPROC) as pool, open(LOG, "a") as f:
        for res in pool.imap_unordered(work, jobs, chunksize=4):
            for line in res: f.write(line + "\n")
            f.flush()


def work(job):
    fields, shape, Cs, Frs, prms, TLIM, MAXORB, v = CTX
    gs, g = job
    auts = []
    for gen in gs:
        auts.append(blockdiag([matpow_mod(C, a, p)
                               if a else np.eye(C.shape[0], dtype=np.int64)
                               for C, a, (p, e) in zip(Cs, gen, fields)]))
    if g is not None:
        auts.append(blockdiag([matpow_mod(F, a, p)
                               if a else np.eye(F.shape[0], dtype=np.int64)
                               for F, a, (p, e) in zip(Frs, g, fields)]))
    try:
        P = AbelianPDS(tuple(shape), extra_auts=auts)
    except Exception as ex:
        return [f"{job!r}\tERR {ex}"]
    if P.norb > MAXORB or P.norb < int(os.environ.get("MINORB", "0")):
        return [f"{job!r}\tSKIP orb={P.norb}"]
    out = []
    for (k, la, mu) in prms:
        t = time.time()
        sols, st = P.search(k, la, mu, time_limit=TLIM, workers=1)
        if sols:
            A = P.cayley(sols[0]); ok = is_srg(A, k, la, mu)
            st = "FOUND" if ok else "FOUND-BAD"
            if ok:
                os.makedirs("hits_abelian", exist_ok=True)
                with open(f"hits_abelian/srg{v}_{k}_{la}_{mu}.g6", "a") as f: f.write(graph6(A) + "\n")
                with open(f"hits_abelian/srg{v}_{k}_{la}_{mu}.pds", "a") as f:
                    f.write(f"{fields} job={job!r}\t{P.elements(sols[0]).tolist()}\n")
        out.append(f"{job!r}\t({k},{la},{mu})\t{st}\torb={P.norb}\t{time.time()-t:.1f}s")
    return out


if __name__ == "__main__":
    main()
